#!/usr/bin/env python3
"""Write the ciderdarling-bin AUR recipe for a prebuilt Arch Linux archive.

  aur-package.py --manifest dist/ciderdarling-<revision>-x86_64-arch.json --output dist/aur

The recipe installs the archive's tree into /opt/ciderdarling/<revision>, where
Cider finds CiderDarling, keeps bin/darling setuid root and restores the file
capability that `cmake --install` sets. Its dependencies are the packages that
own the host libraries the build links and its native bridges load (resolved
with pacman on an Arch host, otherwise from a fixed table). Run
`makepkg --printsrcinfo > .SRCINFO` next to the result before publishing.
"""
import argparse
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys
import time

PACKAGE = "ciderdarling-bin"
REPOSITORY = "https://github.com/CiderHQ-org/CiderDarling"
FILE_CAPABILITIES = {"libexec/darling/usr/sbin/fseventsd": "cap_sys_admin=ep"}
# Fallback when pacman cannot say: soname prefix -> Arch package.
KNOWN = {
    "libc.so": "glibc", "libm.so": "glibc", "libstdc++.so": "libstdc++", "libgcc_s.so": "libgcc",
    "libGL.so": "libglvnd", "libEGL.so": "libglvnd", "libavcodec.so": "ffmpeg", "libavformat.so": "ffmpeg",
    "libavutil.so": "ffmpeg", "libswresample.so": "ffmpeg", "libcairo.so": "cairo", "libdbus-1.so": "dbus",
    "libfontconfig.so": "fontconfig", "libfreetype.so": "freetype2", "libfuse.so": "fuse2",
    "libgif.so": "giflib", "libjpeg.so": "libjpeg-turbo", "libpng16.so": "libpng", "libpulse.so": "libpulse",
    "libtiff.so": "libtiff", "libX11.so": "libx11", "libXcursor.so": "libxcursor", "libXext.so": "libxext",
    "libxkbfile.so": "libxkbfile", "libXrandr.so": "libxrandr",
}
# Loaded by soname through Mesa/libglvnd or the Vulkan loader, not by Darling itself.
EXTRA_DEPENDS = ["vulkan-icd-loader"]


def owner(soname, resolve):
    if resolve and shutil.which("pacman") and shutil.which("ldconfig"):
        listing = subprocess.run(["ldconfig", "-p"], capture_output=True, text=True).stdout
        for line in listing.splitlines():
            fields = line.split()
            if fields and fields[0] == soname and "x86-64" in line:
                result = subprocess.run(["pacman", "-Qoq", fields[-1]], capture_output=True, text=True)
                if result.returncode == 0 and result.stdout.strip():
                    return result.stdout.split()[0]
    for prefix, package in KNOWN.items():
        if soname == prefix or soname.startswith(prefix + "."):
            return package
    return None


def recipe(manifest, depends):
    revision = manifest["source_revision"]
    archive = manifest["archive"]
    date = time.strftime("%Y%m%d", time.gmtime(manifest["source_date"]))
    tag = "bin-" + revision[:12]
    capabilities = "\n".join(
        f"  setcap {value} /opt/ciderdarling/{revision}/{path} 2>/dev/null ||\n"
        f"    echo 'ciderdarling-bin: could not set {value} on {path}'"
        for path, value in FILE_CAPABILITIES.items())
    quoted = " ".join(f"'{name}'" for name in depends)
    pkgbuild = f"""# Maintainer: CiderHQ <https://github.com/CiderHQ-org>
# Generated by tools/cider/aur-package.py from the release manifest of CiderDarling {revision[:12]}.
pkgname={PACKAGE}
_revision={revision}
pkgver={date}.{revision[:9]}
pkgrel=1
pkgdesc="Darling with CiderHQ's fixes for running the macOS Roblox client (prebuilt for Arch Linux)"
arch=('x86_64')
url="{REPOSITORY}"
license=('GPL-3.0-only')
depends=({quoted})
optdepends=('ciderhq: the Cider launcher for Roblox')
provides=('ciderdarling')
conflicts=('ciderdarling')
options=('!strip' '!debug' '!lto')
install={PACKAGE}.install
source=("${{url}}/releases/download/{tag}/{archive}")
noextract=('{archive}')
sha256sums=('{manifest["archive_sha256"]}')

package() {{
  install -d "$pkgdir/opt/ciderdarling" "$pkgdir/usr/bin"
  bsdtar -xpf "$srcdir/{archive}" -C "$pkgdir/opt/ciderdarling"
  chmod 4755 "$pkgdir/opt/ciderdarling/$_revision/bin/darling"
  ln -s "/opt/ciderdarling/$_revision/bin/darling" "$pkgdir/usr/bin/ciderdarling"
}}
"""
    install = f"""post_install() {{
{capabilities}
}}

post_upgrade() {{
  post_install
}}
"""
    return pkgbuild, install


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--resolve-depends", action="store_true",
                        help="ask pacman which packages own the libraries (on the Arch build host)")
    args = parser.parse_args()
    manifest = json.loads(args.manifest.read_text())
    if (manifest.get("schema_version") != 1 or manifest.get("name") != "CiderDarling"
            or not re.fullmatch(r"[0-9a-f]{40}", manifest.get("source_revision", ""))
            or not re.fullmatch(r"[0-9a-f]{64}", manifest.get("archive_sha256", ""))
            or not isinstance(manifest.get("source_date"), int)):
        sys.exit("Not a CiderDarling release manifest with a source date: %s" % args.manifest)
    if manifest.get("flavor") != "arch":
        sys.exit("ciderdarling-bin needs the Arch Linux build (flavor %r)" % manifest.get("flavor"))
    depends, unknown = set(EXTRA_DEPENDS), []
    for soname in manifest.get("shared_libraries", []) + manifest.get("native_libraries", []):
        package = owner(soname, args.resolve_depends)
        if package:
            depends.add(package)
        else:
            unknown.append(soname)
    if unknown:
        sys.exit("No package known for: %s" % ", ".join(sorted(unknown)))
    pkgbuild, install = recipe(manifest, sorted(depends))
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "PKGBUILD").write_text(pkgbuild)
    (args.output / f"{PACKAGE}.install").write_text(install)
    print(f"{args.output / 'PKGBUILD'}: {PACKAGE} {pkgbuild.split('pkgver=')[1].split()[0]}, "
          f"depends on {', '.join(sorted(depends))}")


if __name__ == "__main__":
    main()
